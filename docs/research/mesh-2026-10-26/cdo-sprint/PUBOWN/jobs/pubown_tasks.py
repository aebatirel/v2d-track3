"""PUBOWN box task lists (PLAN.md): one shell command per line, run in parallel by pubown_box.sh (xargs -P). Each
line: cd to the results folder, run, log to logs/<stage>/<label>.log, append 'OK|FAIL <label> <sec>s' to
status/<stage>.txt (C0b's wrap()).
Usage: pubown_tasks.py STAGE --plan plan.json --env env.json > tasks.txt
  STAGE in sigma, markers, params, build, check, fid;  'candidates' prints the json list of built candidates
env.json: {"PY", "REPO", "R" (results), "IN" (inputs), "DEPTH" (unused), "KIT", "STRIDE"}; REPO = the code tree
extracted at the C0b box commit (pubown_freeze.sh), from which every builder, c0b_prep and c0b_tasks is run.

The flags are C0b's, generated by C0b's own code wherever C0b has a per-episode build: this module imports
cdo-sprint/C0b/jobs/c0b_tasks.py (chain, fmt, params, candidates, wrap, py) and gets the pot / lid / blue-cup / beige
build lines from `c0b_tasks.py build` run on a C0b-shaped plan view whose candidate episodes are the PUBOWN episodes
(rack empty, no merged cup). The rack is the one change: `prim_rack.py run` once per episode (--episodes <e>, own
floor depth and own wall thickness) with C0b's flags, instead of one run over five episodes.
Ground truth is never an input: our tracks, C0b's observed points and our own outputs only.
"""
import importlib, json, os, subprocess, sys

CT = None      # c0b_tasks of the frozen code tree (load_ct)
C0BJ = None


def load_ct(env):
    global CT, C0BJ
    C0BJ = f'{env["REPO"]}/docs/research/mesh-2026-10-26/cdo-sprint/C0b/jobs'
    sys.path.insert(0, C0BJ)
    CT = importlib.import_module('c0b_tasks')
    assert os.path.dirname(os.path.abspath(CT.__file__)) == os.path.abspath(C0BJ), CT.__file__

OBJS = ('white_pot', 'white_pot_lid', 'plastic_dish_rack', 'blue_cup', 'beige_cup')
RACK_VARIANTS = ('full', 'nomk')   # C0b's per-episode rack family (joint variants are multi-episode)


def view(plan):
    """C0b-shaped plan for c0b_tasks: candidate episodes = the PUBOWN pairs, rack handled here (empty there)."""
    ce = {o: list(plan['obj_eps'].get(o, [])) for o in OBJS}
    ce['plastic_dish_rack'] = []
    return dict(episodes=plan['episodes'], candidate_eps=ce, all_set={o: el for o, el in plan['obj_eps'].items()},
                marker_objects=plan['marker_objects'])


def base(o, e):
    return f'ep{e}_beige_cup_sep' if o == 'beige_cup' else f'ep{e}_{o}'


def obs_file(env, o, e):
    return f'{env["R"]}/pts/B/{base(o, e)}.npz'


def params(plan, env):
    R = env['R']
    out = CT.params(view(plan), env)                       # pot, lid, blue cup per episode, beige: C0b's own rule
    out['targets'].pop('cup/merged', None)                 # multi-episode build: not part of PUBOWN
    t0 = out['t0_c0b_m']
    for e in plan['obj_eps'].get('plastic_dish_rack', []):
        f = obs_file(env, 'plastic_dish_rack', e)
        t, src = CT.chain([f'{R}/thick/{base("plastic_dish_rack", e)}.npy'], t0)
        out['targets'][f'rack/ep{e}'] = dict(obs=[f], t_wall_m=t, t_src=src + ' (own episode only)')
    out['rule'] = 'C0b PREREG 3.3 chain per (episode, object) on its own measurements; t0_C0b from the C0b run'
    return out


def candidates(plan, env):
    R = env['R']
    C = [c for c in CT.candidates(view(plan), env)
         if c['object'] != 'plastic_dish_rack' and c['episode'] not in ('merged', 'joint', 'all')]
    for e in plan['obj_eps'].get('plastic_dish_rack', []):
        for v in RACK_VARIANTS:
            C.append(dict(object='plastic_dish_rack', label=f'rack/ep{e}/{v}', episode=str(e), variant=v,
                          path=f'{R}/cand/rack/ep{e}/plastic_dish_rack/ep{e}_{v}.glb'))
    for c in C:
        c['pair'] = f'ep{c["episode"]}/{c["object"]}'
    return C


def main():
    stage = sys.argv[1]
    a = dict(zip(sys.argv[2::2], sys.argv[3::2]))
    plan = json.load(open(a['--plan'])); env = json.load(open(a['--env']))
    load_ct(env)
    R, IN = env['R'], env['IN']
    p = CT.paths(env); S, PREP = p['S'], p['PREP']
    E = plan['episodes']
    out = []
    if stage == 'sigma':        # gmg A.2 sigma of the pairs C0b did not measure (C0b's command)
        for o, e in plan['recompute']['sigma']:
            f = obs_file(env, o, e)
            out.append(CT.wrap('sigma', f'{CT.SHORT[o]}/ep{e}',
                               CT.py(env, PREP, 'sigma', f, f'{IN}/sweep/ep{e}/poses.npz', o, ','.join(E[str(e)]['slot']),
                                     f'{R}/sigma/{base(o, e)}.json'), env))
    elif stage == 'markers':    # gmg detect_episode over the episode's prim objects, where C0b's set differs
        for e in plan['recompute']['markers']:
            specs = [f'{o}={obs_file(env, o, e)}={R}/sigma/{base(o, e)}.json' for o in plan['marker_objects'][e]]
            cmd = CT.py(env, PREP, 'markers', e, f'{IN}/sweep/ep{e}/poses.npz', ','.join(E[str(e)]['slot']),
                        f'{R}/markers/ep{e}.json', *specs)
            out.append(CT.wrap('markers', f'ep{e}', cmd, env))
    elif stage == 'params':
        json.dump(params(plan, env), open(f'{R}/params.json', 'w'), indent=1)
        print(f'{R}/params.json'); return
    elif stage == 'build':
        vp = f'{R}/plan_c0bview.json'
        json.dump(view(plan), open(vp, 'w'), indent=1)
        r = subprocess.run([sys.executable, '-I', f'{C0BJ}/c0b_tasks.py', 'build', '--plan', vp, '--env', a['--env']],
                           capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'c0b_tasks build failed: {r.stderr[-2000:]}')
        out += [l for l in r.stdout.splitlines() if l.strip()]
        P = json.load(open(f'{R}/params.json'))['targets']
        for e in plan['obj_eps'].get('plastic_dish_rack', []):
            d = P[f'rack/ep{e}']
            cmd = 'PRIM_CUP_LEAN=1 ' + CT.py(env, f'{S}/prim_rack.py', 'run', '--obs_dir', p['B'], '--out',
                                             f'{R}/cand/rack/ep{e}', '--episodes', str(e), '--t_wall', CT.fmt(d['t_wall_m']),
                                             '--s0_min_t', '--markers_dir', f'{R}/markers')
            out.append(CT.wrap('build', f'rack/ep{e}', cmd, env))
    elif stage == 'candidates':
        print(json.dumps([c for c in candidates(plan, env) if os.path.exists(c['path'])], indent=1)); return
    elif stage == 'check':      # C0b section 5.1 exclusions (watertight raw, kit budget)
        for c in candidates(plan, env):
            if os.path.exists(c['path']):
                outj = f'check/{CT.SHORT[c["object"]]}/' + c['label'].replace('/', '__') + '.json'
                out.append(CT.wrap('check', c['label'], CT.py(env, f'{p["JOB"]}/c0b_check.py', env['KIT'], c['path'], outj), env))
    elif stage == 'fid':        # obs_fidelity.py defaults on the pair's OWN points only (no other episode)
        for c in candidates(plan, env):
            if os.path.exists(c['path']):
                lab = c['label'] + '@own'
                cmd = CT.py(env, f'{S}/obs_fidelity.py', obs_file(env, c['object'], c['episode']), c['path']) + \
                    f' > fid/{CT.SHORT[c["object"]]}/' + lab.replace('/', '__') + '.jsonl'
                out.append(CT.wrap('fid', lab, cmd, env))
    else:
        sys.exit(f'unknown stage {stage}')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
