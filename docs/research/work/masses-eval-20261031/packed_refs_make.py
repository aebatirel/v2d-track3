"""Writes packed_refs.json: per eval episode, the packed policy's stored reference and where a masses retrain pulls it
(2026-10-31, masses eval retrain; PLAN.md section 1). Inputs, all our own files (no ground truth): rank/motion.json
(md5 and mass_arm.traj_fingerprint of the reference files pack 6's box evaluated with), pack 7's checkpoints.json
(packed run, checkpoint and sha256) and the source runs / packed checkpoints listed below (store listing of 29 Oct and
the packed checkpoints' saved configs). Usage: python -I packed_refs_make.py <repo> > packed_refs.json
"""
import json, sys
R = sys.argv[1]
mo = json.load(open(f'{R}/docs/research/work/masses-eval-20261031/rank/motion.json'))
p7 = json.load(open(f'{R}/results/submissions/20261030-track3g-candidate/checkpoints.json'))
PACK31, SEED43 = '20261024-pack-31ef267', '20261024-seed43-61101f5'
GL3 = ['rest_check.json', 'zero_score.txt', 'support_fill.json']
# ep: (mode, source run of the stored reference, packed seed, pieces, lib, per-episode env, glock result files)
SRC = {1: ('std', PACK31, 43, 'meshes/carve/ev01', 'library_v3', '', []),
       3: ('glock', PACK31, 43, None, 'library_v3', '', GL3), 5: ('glock', PACK31, 43, None, 'library_v3', '', GL3),
       6: ('glock', PACK31, 42, None, 'library_v3', '', GL3),
       8: ('glock', '20261025-evb0810-ee7ba8e', 42, None, 'library_v3x', '', GL3),
       10: ('glock', '20261026-gl10A2-5e0e100', 42, 'meshes/carve/ev10', 'library_v3', '', ['rest_check.json', 'zero_score.txt']),
       14: ('glock', '20261025-evb1420-ee7ba8e', 42, None, 'library_v3', '', GL3),
       15: ('glock', PACK31, 43, None, 'library_v3', '', GL3), 16: ('glock', PACK31, 43, None, 'library_v3', '', GL3),
       19: ('std', '20261025-std1928-ee7ba8e', 42, None, 'library_v3', '', []),
       20: ('glock', '20261025-evb1420-ee7ba8e', 42, None, 'library_v3', '', GL3),
       25: ('std', '20261026-c25s42-feb0407', 42, 'meshes/carve/ev25', 'library_v3', '', []),
       28: ('std', PACK31, 42, None, 'library_v3', '', []),
       30: ('std', '20261025-std30-ee7ba8e', 42, None, 'library_v3', '', []),
       32: ('glock', '20261026-fr32s46b-5e0e100', 46, None, 'library_v3', '', GL3),
       33: ('glock', '20261026-fr3233s43-6a8a0e2', 43, None, 'library_v3', 'CURR_SCALE=0.4', GL3),
       35: ('glock', PACK31, 42, None, 'library_v3', '', GL3), 36: ('glock', PACK31, 42, None, 'library_v3', '', GL3),
       37: ('glock', PACK31, 42, None, 'library_v3', '', GL3), 38: ('glock', PACK31, 42, None, 'library_v3', '', GL3)}
out = dict(_note='Generated by packed_refs_make.py (2026-10-31). md5 / fingerprint: the reference file the packed policy '
           'was trained and evaluated on (pack 6 box copy; for std the refs/perc2mcks file, a byte copy of the pulled '
           'refs/perc2mck processed parquet). recipe_checkpoint: the saved config a retrain must reproduce (config diff, '
           'tools/mass_eval_verify.py); for eval 1 the carve recipe c01s43 (pack-8 candidate), else the pack-7 checkpoint. '
           'asset_root: where the reference URDFs live (grasp lock: its own refs/sf copy; eval 10 and std: /content/assets).',
           episodes={})
for ep, (mode, src, seed, pieces, lib, env, gfiles) in SRC.items():
    m, c = mo[str(ep)], p7[str(ep)]
    roots = sorted({u.rsplit('/urdf/', 1)[0] for u in m['urdf_paths']})
    assert len(roots) == 1, (ep, roots)
    pull = ([f'refs/perc2mck/ep{ep}', f'perc2/ep{ep}'] if mode == 'std' else
            [f'refs/perc2mck/ep{ep}'] + ([f'refs/sf/ep{ep}'] if roots[0] != '/content/assets' else []) + [f'refs/glockt/ep{ep}'])
    recipe = (f'runs/20261030-c01s43-328139c/runs/perc2mcks/ep1-s43/policy_250003456.safetensors' if ep == 1 else c['checkpoint'])
    out['episodes'][str(ep)] = dict(
        mode=mode, source_run=src, base='mck', pull=pull,
        result_files=[f'runs/{src}/results/glock_public/ep{ep}/{f}' for f in gfiles],
        reference=m['reference'], md5=m['md5'], traj_fingerprint=m['traj_fingerprint'], asset_root=roots[0],
        objects=list(m['objects']), frames=m['frames'], packed_run=c['run'], packed_checkpoint=c['checkpoint'],
        packed_sha256=c['sha256'], packed_seed=seed, recipe_checkpoint=recipe,
        steps=250003456 if mode == 'std' else 70004736, pieces=pieces, lib=lib, env=env)
print(json.dumps(out, indent=1))
